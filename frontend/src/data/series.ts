const makeSeasons = (seriesId: string, seasons: number, episodesPerSeason: number): ReadonlyArray<Season> =>
  Array.from({ length: seasons }, (_, i) => ({
    seasonNumber: i + 1,
    title: `Season ${i + 1}`,
    episodes: makeEpisodes(seriesId, i + 1, episodesPerSeason, i * episodesPerSeason),
  }));

