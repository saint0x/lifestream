import type { Series, Episode, Season } from "@/types";
import { img } from "./images";

const makeEpisodes = (
  seriesId: string,
  seasonNumber: number,
  count: number,
  offset = 0,
): ReadonlyArray<Episode> =>
  Array.from({ length: count }, (_, i) => {
    const ep = i + 1;
    return {
      id: `${seriesId}-s${seasonNumber}e${ep}`,
      seriesId,
      seasonNumber,
      episodeNumber: ep,
      title: episodeTitles[(offset + i) % episodeTitles.length] ?? "Untitled",
      synopsis:
        "A pivotal turn forces the crew to confront a secret that has been hiding in plain sight since the day they arrived.",
      durationSec: 2700 + ((i * 137) % 900),
      airedAt: `2025-${String(((seasonNumber - 1) * 3 + 1) % 12 || 1).padStart(2, "0")}-${String((ep * 7) % 27 || 1).padStart(2, "0")}`,
      thumbnail: img.thumbnail(`${seriesId}-${seasonNumber}-${ep}`),
    };
  });

