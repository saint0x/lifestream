// 30 days of analytics data — built algorithmically for variety.
export const analytics30d: ReadonlyArray<AnalyticsPoint> = Array.from(
  { length: 30 },
  (_, i) => {
    const day = 29 - i;
    const date = new Date(now.getTime() - day * 86_400_000)
      .toISOString()
      .slice(0, 10);
    const base = 8_000 + Math.round(Math.sin(i / 3) * 2_400);
    const weekend = [0, 6].includes(
      new Date(now.getTime() - day * 86_400_000).getDay(),
    );
    const viewers = base + (weekend ? 2_800 : 0) + ((i * 317) % 1_200);
    const watchMinutes = viewers * (42 + ((i * 7) % 18));
    const revenue = Math.round(viewers * 0.042 * 100) / 100;
    const newFollowers = Math.round(viewers / 48) + ((i * 13) % 60);
    return { date, viewers, watchMinutes, revenue, newFollowers };
  },
);

